"""Write scripts/levels/sedge_plain/sedge_layout.gd, the level data gameplay loads, from layout.py.

    python tools/levels/sedge_plain/export_layout.py <out.gd>

Everything in it is generated: markers, hollows (CurseField slots), the safe ground (causeway
polylines with half widths, island and plateau discs), the paths, the Seam, the tie pairs, the
sealed fights and the prop placements. Do not edit the .gd by hand; change layout.py and rerun.
"""
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import layout as L  # noqa: E402


def v2(p):
    return "Vector2(%.2f, %.2f)" % (p[0], p[1])


def v3(p):
    return "Vector3(%.2f, %.2f, %.2f)" % tuple(p)


def arr2(pts):
    return "[" + ", ".join(v2(p) for p in pts) + "]"


def main(out):
    m = L.markers()
    lines = [
        "class_name SedgePlainLayout",
        "extends RefCounted",
        "## Sedge Plain level data, generated by tools/levels/sedge_plain/export_layout.py from",
        "## tools/levels/sedge_plain/layout.py (the same data the terrain and the plan are built from).",
        "## Do not edit by hand. Godot axes, metres: X east, Y up, Z south. Owner: l3.",
        "",
        "## Every marker, as placed on the terrain (scenes/levels/sedge_plain/terrain.tscn carries the same).",
        "const MARKERS := {",
    ]
    lines += ['\t"%s": %s,' % (k, v3(p)) for k, p in m.items()]
    lines += ["}", "", "## The cursed hollows: CurseField slot, zone centre and radius, rim radius, floor height.", "const HOLLOWS := {"]
    for key, ho in L.HOLLOWS.items():
        cx, cz = ho["c"]
        lines.append('\t&"%s": {"name": "%s", "slot": %d, "center": %s, "zone_radius": %.2f, "rim_radius": %.2f, "floor_y": %.2f},' % (
            key, ho["name"], ho["slot"], v3((cx, L.hollow_floor_y(key), cz)), ho["zone_r"], ho["rim_r"], L.hollow_floor_y(key)))
    lines += ["}", "", "## Safe ground inside the hollows: polylines (x, z) with a half width in metres.", "const SAFE_LINES := ["]
    for key, cw in L.CAUSEWAYS.items():
        lines.append('\t{"name": "causeway_%s", "half_width": %.2f, "points": %s},' % (key, cw["half"], arr2(cw["pts"])))
    lines.append('\t{"name": "knoll_ramp", "half_width": %.2f, "points": %s},' % (L.KNOLL_RAMP_HALF, arr2(L.KNOLL_RAMP)))
    lines += ["]", "## Safe discs: x, z and radius (the two islands and the Knoll's plateau).", "const SAFE_DISCS := ["]
    for key, ((ix, iz), r) in L.ISLANDS.items():
        lines.append("\tVector3(%.2f, %.2f, %.2f),  # island %s" % (ix, iz, r, key))
    lines.append("\tVector3(%.2f, %.2f, %.2f),  # the Knoll" % (L.KNOLL_C[0], L.KNOLL_C[1], L.KNOLL_TOP_R))
    lines += ["]", "", "## Paths on the open plain (sand on the ground texture), for routes and foliage clearance.", "const PATHS := {"]
    for key, pts in L.PATHS.items():
        lines.append('\t&"%s": %s,' % (key, arr2(pts)))
    lines += ["}", "## Centre line of the Seam (the dry gully), its half width at the lip and its depth.",
              "const SEAM := %s" % arr2(L.SEAM), "const SEAM_HALF_WIDTH := %.2f" % L.SEAM_TOP_HALF, "const SEAM_DEPTH := %.2f" % L.SEAM_DEPTH, "",
              "## Tie anchors: pairs of marker names (two bridges over the Seam, the break in the Mere causeway).",
              'const TIE_PAIRS := [["M_Bridge1_S", "M_Bridge1_N"], ["M_Bridge2_S", "M_Bridge2_N"], ["M_Tie_Break_A", "M_Tie_Break_B"]]', "",
              "## Sealed fights: centre marker, ring radius, patrol radius for roaming packs, pack.", "const FIGHTS := {"]
    for k, f in L.FIGHTS.items():
        lines.append('\t&"fight_%s": {"marker": "M_Fight_%s", "radius": %.1f, "patrol": %.1f, "pack": "%s"},' % (k, k, f["r"], f["patrol"], f["pack"]))
    lines += ["}", "", "## Prop placements: [model, position, yaw degrees, scale].", "const PROPS := ["]
    for model, x, y, z, yaw, s in L.props():
        lines.append('\t["%s", Vector3(%.2f, %.2f, %.2f), %.1f, %.2f],' % (model, x, y, z, yaw, s))
    lines += ["]", "", "",
              "## True when p stands on clean ground inside a hollow (a causeway, island, ramp or the plateau).",
              "static func is_safe(p: Vector3, margin: float = 0.0) -> bool:",
              "\tvar q := Vector2(p.x, p.z)",
              "\tfor d: Vector3 in SAFE_DISCS:",
              "\t\tif q.distance_to(Vector2(d.x, d.y)) < d.z + margin:",
              "\t\t\treturn true",
              "\tfor line: Dictionary in SAFE_LINES:",
              "\t\tif polyline_distance(q, line[\"points\"]) < float(line[\"half_width\"]) + margin:",
              "\t\t\treturn true",
              "\treturn false",
              "",
              "",
              "## The hollow whose rim p lies inside, or &\"\".",
              "static func hollow_at(p: Vector3) -> StringName:",
              "\tfor key: StringName in HOLLOWS:",
              "\t\tvar h: Dictionary = HOLLOWS[key]",
              "\t\tvar c: Vector3 = h[\"center\"]",
              "\t\tif Vector2(p.x - c.x, p.z - c.z).length() < float(h[\"rim_radius\"]):",
              "\t\t\treturn key",
              "\treturn &\"\"",
              "",
              "",
              "## Ground that keeps you out: inside a hollow's rim and below the plain, and not safe.",
              "static func is_kept_out(p: Vector3) -> bool:",
              "\tvar key := hollow_at(p)",
              "\tif key == &\"\":",
              "\t\treturn false",
              "\treturn not is_safe(p)",
              "",
              "",
              "static func polyline_distance(q: Vector2, pts: Array) -> float:",
              "\tvar best := INF",
              "\tfor i in pts.size() - 1:",
              "\t\tvar a: Vector2 = pts[i]",
              "\t\tvar b: Vector2 = pts[i + 1]",
              "\t\tvar ab := b - a",
              "\t\tvar t := clampf((q - a).dot(ab) / maxf(ab.length_squared(), 0.0001), 0.0, 1.0)",
              "\t\tbest = minf(best, q.distance_to(a + ab * t))",
              "\treturn best",
              ""]
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("LAYOUT %s markers=%d props=%d" % (Path(out).name, len(m), len(L.props())))


if __name__ == "__main__":
    main(sys.argv[1])
