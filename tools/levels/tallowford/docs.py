"""Writes docs/levels/tallowford/SCRIPT.md from scripts/levels/tallowford/script.json, and the
generated tables in docs/levels/tallowford/DESIGN.md (markers, people, props) from layout.py,
so the documents cannot drift from the data phase B loads.

    python tools/levels/tallowford/docs.py
"""
import json
import re
import sys
from collections import Counter
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))
import layout as L  # noqa: E402

DOCS = ROOT / "docs/levels/tallowford"


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def script_md():
    data = json.loads((ROOT / "scripts/levels/tallowford/script.json").read_text(encoding="utf-8"))
    sp = data["speakers"]
    out = ["# Tallowford: the script", "",
           "Generated by `tools/levels/tallowford/docs.py` from `scripts/levels/tallowford/script.json`, which is",
           "the data phase B loads. Edit the JSON, then re-run the script.", "",
           data["markup"], "", "## Voices", "", "| Speaker id | Name | Voice |", "| - | - | - |"]
    for k, v in sp.items():
        out.append("| %s | %s | %s |" % (k, v["name"] or "(none)", v["voice"]))
    beat_names = {0: "Arrival", 1: "Beat 1: Old Trim", 2: "Beat 2: Marrow the dyer", 3: "Beat 3: Brindle the well-keeper",
                  4: "Beat 4: the children's house", 5: "Beat 5: the ferry-house and the first sealed fight",
                  6: "Beat 6: the ford-lamp, the finale and after"}
    beat = None
    count = Counter()
    for sc in data["scenes"]:
        if sc["beat"] != beat:
            beat = sc["beat"]
            out += ["", "## " + beat_names[beat]]
        out += ["", "### %s" % sc["id"], "", "*Trigger:* %s *At:* `%s`." % (sc["trigger"], sc["where"]), ""]
        for who, text in sc["lines"]:
            count[who] += 1
            name = sp[who]["name"]
            if who == "verse":
                out.append("> %s  " % text)
            elif who == "narration":
                out.append("- *%s*" % text)
            elif who == "prompt":
                out.append("- **Prompt:** %s" % text)
            else:
                out.append("- **%s:** %s" % (name, text))
    total = sum(count.values())
    out += ["", "## Counts", "", "%d scenes, %d lines: %s." % (len(data["scenes"]), total,
            ", ".join("%s %d" % (k, v) for k, v in sorted(count.items(), key=lambda kv: -kv[1])))]
    write(DOCS / "SCRIPT.md", "\n".join(out) + "\n")
    print("SCRIPT.md", len(data["scenes"]), "scenes", total, "lines")


def tables():
    m = L.all_markers()
    rows = ["| Marker | x | y | z |", "| - | - | - | - |"]
    for k in sorted(m):
        if k.startswith("M_Person_"):
            continue
        x, y, z = m[k]
        rows.append("| %s | %.2f | %.2f | %.2f |" % (k, x, y, z))
    people = ["| Marker | x | y | z | Facing (yaw, degrees) |", "| - | - | - | - | - |"]
    for k, (p, yaw) in L.people().items():
        people.append("| %s | %.2f | %.2f | %.2f | %.0f |" % (k, p[0], L.ground(*p), p[1], yaw))
    props = ["| Model | x | y | z | Yaw | Scale |", "| - | - | - | - | - | - |"]
    for model, x, z, yaw, s in L.props():
        props.append("| %s | %.2f | %.2f | %.2f | %.0f | %.2f |" % (model, x, L.prop_y(model, x, z), z, yaw, s))
    return {"markers": "\n".join(rows), "people": "\n".join(people), "props": "\n".join(props)}


def design_md():
    path = DOCS / "DESIGN.md"
    text = path.read_text(encoding="utf-8")
    for key, body in tables().items():
        pat = re.compile(r"(<!-- %s:begin -->\n).*?(<!-- %s:end -->)" % (key, key), re.S)
        if not pat.search(text):
            raise SystemExit("DESIGN.md has no %s block" % key)
        text = pat.sub(lambda mm: mm.group(1) + body + "\n" + mm.group(2), text)
    write(path, text)
    print("DESIGN.md tables updated")


if __name__ == "__main__":
    script_md()
    if (DOCS / "DESIGN.md").exists():
        design_md()
